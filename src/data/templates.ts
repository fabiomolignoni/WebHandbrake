/**
 * Built-in templates: the ready-made lists of the rule wizard and editor. They live in this data
 * file so that the community can review and extend them without touching code.
 *
 * Each entry is a line in the address syntax of the rule editor (Help › Rules and sites):
 * `example.com` is a site with its subdomains, `=example.com` that host only (with www.),
 * `example.com/feed` a section, `+example.com` an exception. How the entries are chosen:
 *
 * - Only addresses that people open. WebHandbrake stops pages, not the images, scripts and
 *   videos inside them, so content delivery and API domains (ytimg.com, fbcdn.net…) would do
 *   nothing. Official short links that open the service are listed (youtu.be, redd.it): they are
 *   stopped before any request.
 * - One entry per site: subdomains are always included (m.youtube.com, old.reddit.com), and a
 *   country domain that only redirects to a listed one (pinterest.it, amazon.at, poki.de) is left
 *   out. Former domains that old links still use are kept (twitter.com, threads.net, max.com).
 * - Every country domain written out, never `name.*`: a site name with * matches unrelated sites
 *   (crazygames.it is not CrazyGames), makes the page script run on every site and needs a
 *   regular expression filter of the browser.
 * - The distraction, not the tools around it: exceptions keep work and non-distracting services
 *   open (Amazon Web Services and Seller Central, Meta's business tools, YouTube Studio and
 *   YouTube Music), a section blocks only the feed of a site used for work (LinkedIn), and
 *   messaging (Discord, WhatsApp), music and email are in no list.
 * - Alternative front ends that show the same content (Invidious, Piped, Nitter) are listed when
 *   their main instances have lasted; they cannot all be covered.
 *
 * Sources: the services of AdGuard's HostlistsRegistry (github.com/AdguardTeam/HostlistsRegistry)
 * for the domains of each platform, the platforms' own country sites, and a check that every
 * address answered and where it redirected (October 2026). tests/unit/templates.test.ts checks the
 * syntax, duplicates, entries covered by another one and the cost in browser filters.
 */

