/**
 * docs/traceability.md: for each requirement of docs/requirements.md, the tests whose titles cite
 * it and the manual checks of docs/testing.md that start with it; then the circumvention routes of
 * docs/threat-model.md and the tests citing them, and the unverified requirements. Evidence is
 * "file › title", without line numbers, so the file changes only when titles change.
 */

import { SPEC } from '../config.mjs';
import { escapeText, slugger } from '../md.mjs';
import { idPattern, parseManualChecks, parseRequirements, parseRoutes, testEvidence } from '../spec.mjs';

const OUTPUT = 'docs/traceability.md';
const SOURCES = `${SPEC.requirements}, ${SPEC.threatModel}, ${SPEC.testing}#manual-checks and the test titles in tests/`;

/** Plain text (test titles) in a table cell. */
const cell = (s) => escapeText(s, { table: true }).replace(/\n/g, ' ');
/** Markdown written by hand (titles, routes, notes) in a table cell: only pipes are escaped. */
const mdCell = (s) => s.replace(/(?<!\\)\|/g, '\\|').replace(/\n/g, ' ');
const evidenceCell = (list) => list.map((e) => `${cell(e.file)} › ${cell(e.title)}`).join('<br>') || '—';

export default {
  name: 'traceability',
  output: OUTPUT,
  description:
    'docs/traceability.md from the requirements, the threat model, the manual checks and the test titles',
  async generate(repo) {
    const req = repo.doc(SPEC.requirements);
    if (!req) return { skip: `${SPEC.requirements} does not exist` };
    const { items } = parseRequirements(req);
    const tm = repo.doc(SPEC.threatModel);
    const routes = tm ? parseRoutes(tm).routes : [];
    const prefixes = new Set([...items.map((i) => i.id.split('-')[0]), 'CIR']);
    const re = idPattern(prefixes);
    const evidence = testEvidence(repo, re);
    const testing = repo.doc(SPEC.testing);
    const manual = new Map();
    for (const mc of (testing && parseManualChecks(testing)) ?? []) {
      for (const id of mc.ids) manual.set(id, [...(manual.get(id) ?? []), mc]);
    }
    const ev = (id) => evidence.get(id) ?? { unit: [], e2e: [] };
    const link = (id) => `[${id}](requirements.md#${id.toLowerCase()})`;

    const live = items.filter((i) => !['planned', 'withdrawn'].includes(i.status));
    const areas = [];
    for (const item of live) {
      let area = areas.find((a) => a.title === item.area);
      if (!area) areas.push((area = { title: item.area, items: [] }));
      area.items.push(item);
    }
    const slug = slugger();
    slug('Traceability');
    slug('Summary');

    const out = [
      `<!-- GENERATED by npm run docs from ${SOURCES}. Do not edit. -->`,
      '',
      '# Traceability',
      '',
      'Which tests verify each requirement of [the requirements](requirements.md). A test is evidence',
      'for an ID when its title cites the ID, or when the title of a `describe` block around it does.',
      'Manual checks are the lines of [the manual checks](testing.md#manual-checks) that start with the',
      'ID. Planned and withdrawn IDs are listed only in the requirements.',
      '',
      '## Summary',
      '',
      '| Area | Implemented | Partial | Unverified | With unit tests | With e2e tests |',
      '|---|---|---|---|---|---|',
    ];
    const areaSlugs = areas.map((a) => slug(a.title));
    areas.forEach((a, k) => {
      const count = (s) => a.items.filter((i) => i.status === s).length;
      const withKind = (kind) => a.items.filter((i) => ev(i.id)[kind].length).length;
      out.push(
        `| [${mdCell(a.title)}](#${areaSlugs[k]}) | ${count('implemented')} | ${count('partial')} | ${count('unverified')} | ${withKind('unit')} | ${withKind('e2e')} |`,
      );
    });
    const planned = items.filter((i) => i.status === 'planned').length;
    const withdrawn = items.filter((i) => i.status === 'withdrawn').length;
    out.push('', `Planned: ${planned}. Withdrawn: ${withdrawn}.`, '');

    for (const a of areas) {
      out.push(`## ${a.title}`, '');
      out.push(
        '| ID | Title | Status | Verification | Unit tests | E2E tests | Manual |',
        '|---|---|---|---|---|---|---|',
      );
      for (const i of a.items) {
        const manualCell = (manual.get(i.id) ?? []).map((mc) => mdCell(mc.text)).join('<br>') || '—';
        out.push(
          `| ${link(i.id)} | ${mdCell(i.title)} | ${i.status} | ${i.verification.join(', ') || '—'} | ${evidenceCell(ev(i.id).unit)} | ${evidenceCell(ev(i.id).e2e)} | ${manualCell} |`,
        );
      }
      out.push('');
    }

    out.push('## Circumvention routes', '');
    if (!routes.length) out.push(`No routes are listed in [the threat model](threat-model.md).`, '');
    else {
      out.push('| ID | Route | Status | Tests citing it |', '|---|---|---|---|');
      for (const r of routes) {
        const e = ev(r.id);
        const tests = [...e.unit, ...e.e2e];
        out.push(
          `| [${r.id}](threat-model.md#${r.id.toLowerCase()}) | ${mdCell(r.route)} | ${mdCell(r.status)} | ${evidenceCell(tests)} |`,
        );
      }
      out.push('');
    }

    out.push('## Unverified requirements', '');
    const unverified = items.filter((i) => i.status === 'unverified');
    if (!unverified.length) out.push('None.', '');
    const groups = [
      ['Study or measurement', (i) => i.verification.includes('study')],
      ['Manual check', (i) => !i.verification.includes('study') && i.verification.includes('manual')],
      ['Other verification', (i) => !i.verification.includes('study') && !i.verification.includes('manual')],
    ];
    for (const [title, test] of groups) {
      const list = unverified.filter(test);
      if (!list.length) continue;
      out.push(`### ${title}`, '');
      for (const i of list) out.push(`- ${link(i.id)} ${i.title}${i.note ? `: ${i.note}` : ''}`);
      out.push('');
    }
    return `${out.join('\n').replace(/\n+$/, '')}\n`;
  },
};
