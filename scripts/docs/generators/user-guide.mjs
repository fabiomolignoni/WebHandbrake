/**
 * docs/user-guide.md: the in-extension Help page as a Markdown document, for people who read it
 * without installing the extension (store reviewers, Firefox for Android users, search).
 *
 * It renders HELP_TOPICS (src/dashboard/help-content.ts) in order, with the English messages of
 * src/locales/en.json formatted by src/i18n/icu.ts and the parameters of helpFacts() (the
 * defaults), exactly as the Help page does. The shortcuts show each command's default key from
 * scripts/manifest.mjs. The About section and the version are left out, so the file changes only
 * when the Help changes.
 */

import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { escapeText, slugger } from '../md.mjs';
import { loadModules } from '../ts.mjs';

const OUTPUT = 'docs/user-guide.md';
const SOURCES = 'src/locales/en.json, src/dashboard/help-content.ts and scripts/manifest.mjs';

/** The placeholder names of a parsed ICU message, nested ones included. */
function placeholders(nodes, out = new Set()) {
  for (const n of nodes) {
    if (typeof n === 'string' || n.t === 'hash') continue;
    out.add(n.name);
    if (n.options) for (const branch of Object.values(n.options)) placeholders(branch, out);
  }
  return out;
}

export default {
  name: 'user-guide',
  output: OUTPUT,
  description: 'docs/user-guide.md from the Help page (help-content.ts, en.json, the manifest)',
  async generate(repo) {
    const m = await loadModules(repo.root);
    const en = JSON.parse(repo.read('src/locales/en.json'));
    const pkg = JSON.parse(repo.read('package.json'));
    const { manifest } = await import(pathToFileURL(join(repo.root, 'scripts/manifest.mjs')).href);
    const commands = manifest('chrome', pkg.version).commands;
    const facts = m.helpFacts();

    /** A message rendered as the Help page renders it; every placeholder must have a value. */
    const t = (key, params = {}) => {
      const msg = en[key]?.message;
      if (typeof msg !== 'string') throw new Error(`message '${key}' is not in src/locales/en.json.`);
      const missing = [...placeholders(m.parseMessage(msg))].filter((p) => params[p] === undefined);
      if (missing.length)
        throw new Error(
          `${key} uses ${missing.map((p) => `{${p}}`).join(', ')} but its params in src/dashboard/help-content.ts do not provide ${missing.length > 1 ? 'them' : 'it'}.`,
        );
      return m.formatMessage(msg, params, 'en');
    };
    const text = (key, params) => escapeText(t(key, params));
    const slug = slugger();
    slug('WebHandbrake user guide');

    const body = [];
    const contents = [];
    for (const topic of m.HELP_TOPICS) {
      const title = t(topic.title);
      contents.push(`- [${escapeText(title)}](#${slug(title)})`);
      body.push(`## ${escapeText(title)}`, '');
      for (const block of topic.blocks) {
        const params = block.params?.(facts);
        if ('p' in block) body.push(text(block.p, params), '');
        else if ('list' in block) body.push(...block.list.map((key) => `- ${text(key, params)}`), '');
        else if ('q' in block) {
          const q = t(block.q, params);
          slug(q);
          body.push(`### ${escapeText(q)}`, '', text(block.a, params), '');
        } else if ('syntax' in block) {
          body.push(`| ${text('help.syntax.entry')} | ${text('help.syntax.meaning')} |`, '|---|---|');
          for (const [entry, key] of m.SYNTAX) {
            body.push(`| \`${entry.replace(/\|/g, '\\|')}\` | ${escapeText(t(key), { table: true })} |`);
          }
          body.push('');
        } else if ('shortcuts' in block) {
          for (const s of m.SHORTCUTS) {
            const combo = m.defaultShortcut(commands, s.command);
            if (!combo) continue;
            const keys = combo
              .split('+')
              .map((k) => `<kbd>${k}</kbd>`)
              .join('+');
            body.push(`- ${keys} — ${text(s.description, s.params?.(facts))}`);
          }
          body.push('');
        }
      }
    }

    const lines = [
      `<!-- GENERATED by npm run docs from ${SOURCES}. Do not edit. -->`,
      '',
      '# WebHandbrake user guide',
      '',
      'This is the Help page of WebHandbrake (**Dashboard › Help**), generated from the extension so',
      'that it can be read without installing it. Where a number depends on a setting, it is the default.',
      '',
      ...contents,
      '',
      ...body,
    ];
    return `${lines.join('\n').replace(/\n+$/, '')}\n`;
  },
};
