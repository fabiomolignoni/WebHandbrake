/**
 * docs/adr/README.md: the list of architecture decision records, from the H1 and the header lines
 * of each docs/adr/NNNN-*.md (the template, 0000, is not listed).
 */

const OUTPUT = 'docs/adr/README.md';
const TEMPLATE = 'docs/adr/0000-template.md';

/** The number, title and header lines of an ADR. */
export function readAdr(text) {
  const lines = text.split('\n');
  const h1 = lines.find((l) => /^# /.test(l)) ?? '';
  const m = h1.match(/^# ADR (\d{4}) [—-] (.+)$/);
  const header = {};
  const start = lines.indexOf(h1);
  for (let i = start + 1; i < lines.length; i++) {
    const l = lines[i];
    if (l.trim() === '' && !Object.keys(header).length) continue;
    const kv = l.match(/^- ([A-Za-z ]+):\s*(.*)$/);
    if (!kv) break;
    header[kv[1]] = { value: kv[2].trim(), line: i + 1 };
  }
  return { number: m?.[1] ?? null, title: m?.[2]?.trim() ?? null, h1, header };
}

export default {
  name: 'adr-index',
  output: OUTPUT,
  description: 'docs/adr/README.md from the H1 and header lines of the ADRs',
  async generate(repo) {
    const files = repo.match(/^docs\/adr\/\d{4}-[^/]+\.md$/).filter((p) => p !== TEMPLATE);
    if (!files.length) return { skip: 'docs/adr has no ADR' };
    const rows = files.map((path) => {
      const adr = readAdr(repo.read(path));
      const file = path.slice('docs/adr/'.length);
      const number = adr.number ?? file.slice(0, 4);
      let status = adr.header.Status?.value ?? '—';
      status = status.replace(/ADR (\d{4})/g, (s, n) => {
        const target = files.find((f) => f.startsWith(`docs/adr/${n}-`));
        return target ? `[${s}](${target.slice('docs/adr/'.length)})` : s;
      });
      const title = (adr.title ?? file).replace(/\|/g, '\\|');
      return `| [${number}](${file}) | ${title} | ${status} | ${adr.header.Date?.value ?? '—'} |`;
    });
    const intro = [
      'Each record states one architectural decision: its context, the options considered, the',
      'outcome, its consequences and how it is kept true.',
    ];
    if (repo.exists(TEMPLATE)) intro.push('', 'To record a decision, copy [the template](0000-template.md).');
    const out = [
      '<!-- GENERATED by npm run docs from the H1 and header lines of docs/adr/*.md. Do not edit. -->',
      '',
      '# Architecture decision records',
      '',
      ...intro,
      '',
      '| ADR | Decision | Status | Date |',
      '|---|---|---|---|',
      ...rows,
    ];
    return `${out.join('\n')}\n`;
  },
};
