/** The 15 format bits read around the top-left finder pattern, unmasked (ISO/IEC 18004). */
function formatBits(m: boolean[][]): number {
  const cells: [number, number][] = [];
  for (let i = 0; i <= 5; i++) cells.push([8, i]);
  cells.push([8, 7], [8, 8], [7, 8]);
  for (let i = 9; i < 15; i++) cells.push([14 - i, 8]);
  return cells.reduce((bits, [x, y], i) => bits | (Number(m[y][x]) << i), 0) ^ 0x5412;
}

describe('QR codes for the partner code', () => {
  it('match a reference encoder, byte for byte, with the same mask', () => {
    expect(rows(qrMatrix('otpauth://totp/x?secret=ABC', { mask: 5 }))).toEqual(VERSION_3);
    // Version 7 and above carry version information and several blocks.
    expect(rows(qrMatrix('x'.repeat(120), { mask: 3 }))).toEqual(VERSION_7);
  });

  it('choose the smallest version that holds the text', () => {
    expect(qrMatrix('A')).toHaveLength(21);
    expect(qrMatrix('x'.repeat(14))).toHaveLength(21);
    expect(qrMatrix('x'.repeat(15))).toHaveLength(25);
    // An otpauth address with a 160-bit secret fits in version 6.
    const uri = `otpauth://totp/WebHandbrake%3APartner%20code?secret=${'A'.repeat(32)}&issuer=WebHandbrake`;
    expect(qrMatrix(uri)).toHaveLength(41);
    expect(() => qrMatrix('x'.repeat(214))).toThrow('too long');
  });

  it('have finder patterns, timing patterns and the format of level M with the chosen mask', () => {
    const m = qrMatrix('otpauth://totp/x?secret=ABC');
    const size = m.length;
    for (const [x0, y0] of [
      [0, 0],
      [size - 7, 0],
      [0, size - 7],
    ])
      for (let y = 0; y < 7; y++)
        for (let x = 0; x < 7; x++) {
          const ring = Math.max(Math.abs(x - 3), Math.abs(y - 3));
          expect(m[y0 + y][x0 + x]).toBe(ring !== 2);
        }
    for (let i = 8; i < size - 8; i++) {
      expect(m[6][i]).toBe(i % 2 === 0);
      expect(m[i][6]).toBe(i % 2 === 0);
    }
    const format = formatBits(m);
    expect(format >> 13).toBe(0); // level M
    const mask = (format >> 10) & 7;
    // The mask chosen automatically has the lowest penalty of the eight.
    const scores = [0, 1, 2, 3, 4, 5, 6, 7].map((k) =>
      penalty(qrMatrix('otpauth://totp/x?secret=ABC', { mask: k })),
    );
    expect(scores[mask]).toBe(Math.min(...scores));
  });
});
